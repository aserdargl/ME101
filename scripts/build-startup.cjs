/** Builds the committed GitHub Pages entry point; no deployment service is needed. */
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const sources = [
  'portal-translations.js', 'portal-language.js', 'catalog-order.js', 'catalog-ui.js',
  'pdf-slides.js', 'html-slides.js', 'slide-visual.js', 'pdf-preview.js',
  'lecture-storage.js', 'lecture-document.js', 'google-drive-storage.js', 'drive-publishing.js', 'github-repository.js', 'instructor-repository.js', 'lecture-publishing.js', 'legacy-content.js',
  'student-numbers.js', 'student-session.js', 'firebase-student-service.js', 'firebase-enrollment.js',
  'approval-client.js', 'roster-edit-client.js', 'firebase-adapter.js', 'firebase-students.js', 'approval-ui.js',
  'instructor-login.js', 'roster-table.js', 'registered-roster.js', 'presentation-fullscreen.js', 'presentation-fit.js', 'app.js'
];
const output = '/* Generated by node scripts/build-startup.cjs. Edit the source modules. */\n' + sources.map(source =>
  `\n/* ${source} */\n${fs.readFileSync(path.join(root, source), 'utf8').replace(/\r\n/g, '\n').trimEnd()}\n;\n`
).join('');
const target = path.join(root, 'portal-startup.js');
const version = createHash('sha256').update(output).digest('hex').slice(0, 12);
const htmlPath = path.join(root, 'index.html');
const html = fs.readFileSync(htmlPath, 'utf8');
const versionedHtml = html.replace(/portal-startup\.js\?v=[^"\s]+/, `portal-startup.js?v=${version}`);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output || html !== versionedHtml) {
    console.error('portal-startup.js is stale. Run npm run build.');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, output);
  fs.writeFileSync(htmlPath, versionedHtml);
}
