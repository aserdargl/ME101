/* Synthetic content only; all writes stay on this isolated local origin. */
const assert = require('node:assert/strict');
const { fork } = require('node:child_process');
const path = require('node:path');
const { chromium } = require('playwright');
const origin = 'http://127.0.0.1:4196';

(async () => {
  const server = fork(path.join(__dirname, 'preview-server.cjs'), { env: { ...process.env, MEE101_QA_PORT: '4196' }, silent: true });
  let browser;
  try {
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); });
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
    await page.addInitScript(() => localStorage.setItem('mee101_preferred_view_mode_v1', 'web'));
    await page.goto(origin);
    await page.waitForFunction(() => typeof openLecture === 'function');
    assert.equal(await page.evaluate(() => preferredSlideViewMode), 'web');
    await page.evaluate(async () => {
      const file = new File([await (await fetch('/fixture.pptx')).arrayBuffer()], 'fixture.pptx');
      const slides = await PptxImport.parse(file, 'QA', 'Synthetic');
      slides[0].html = '<p id="qa-note">Preserved notes</p><p class="fragment">Web step</p>';
      slides[1].html = '<p class="fragment">Second web step</p>';
      slides.push({ title: 'Interactive', html: '<button id="qa-interactive" onclick="this.textContent=42">Calculate</button>' });
      const lecture = { id: 'qa-images', week: 'QA', title: 'Synthetic', slides };
      LECTURES.splice(0, LECTURES.length, lecture);
      window.qaOriginal = JSON.stringify(LECTURES);
      await PptxDisplay.prepareUpload(file, slides);
      openLecture(lecture.id);
    });
    const host = page.locator('[data-pptx-render]').first();
    await host.waitFor();
    await page.waitForFunction(() => document.querySelector('[data-pptx-render]')?.dataset.imageReady === 'true', null, { timeout: 30000 });
    assert.equal(await host.locator('img[src^="data:image/png"]').count(), 1);
    assert.match(await host.locator('img[src^="data:image/png"]').getAttribute('src'), /^data:image\/png/);
    const pixels = await host.locator('img[src^="data:image/png"]').evaluate(image => {
      const canvas = document.createElement('canvas');
      canvas.width = image.naturalWidth; canvas.height = image.naturalHeight;
      canvas.getContext('2d').drawImage(image, 0, 0);
      const bytes = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
      let colored = 0;
      for (let i = 0; i < bytes.length; i += 4) if (bytes[i + 3] && Math.max(bytes[i], bytes[i + 1], bytes[i + 2]) - Math.min(bytes[i], bytes[i + 1], bytes[i + 2]) > 40) colored++;
      return colored;
    });
    assert.ok(pixels > 10000, `Expected actual artwork, got ${pixels} colored pixels`);
    await page.locator('#qa-note').waitFor({ state: 'visible' });
    await page.locator('#qa-interactive').click();
    assert.equal(await page.locator('#qa-interactive').textContent(), '42');
    await page.evaluate(() => applyPersistentSlideViewMode('ppt'));
    assert.equal(await host.locator('img[src^="data:image/png"]').isVisible(), false);
    await page.evaluate(() => applyPersistentSlideViewMode('web'));
    await page.locator('.btn-slide-mode-switch').first().selectOption('image');
    assert.equal(await host.locator('img[src^="data:image/png"]').isVisible(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await page.evaluate(() => JSON.stringify(LECTURES) === qaOriginal), true);
    await page.evaluate(() => { goHome(); openLecture('qa-images', true); });
    assert.equal(await page.locator('#btn-pres-view-mode').inputValue(), 'image');
    assert.equal(await page.locator('.slide.active-slide').getAttribute('data-view-mode'), 'image');
    await page.locator('.slide.active-slide img[src^="data:image/png"]').waitFor({ state: 'visible' });
    const nativeFit = await page.locator('.slide.active-slide').evaluate(slide => {
      const image = slide.querySelector('[data-pptx-render]').shadowRoot.querySelector('img[src^="data:image/png"]');
      const rect = image.getBoundingClientRect(), parent = slide.getBoundingClientRect();
      return slide.scrollHeight <= slide.clientHeight + 1 && rect.bottom <= parent.bottom + 1 && rect.top >= parent.top;
    });
    assert.equal(nativeFit, true, 'converted PPTX must fit the presentation card');
    assert.equal(await page.locator('#step-indicator').isVisible(), false);
    await page.locator('#btn-next-slide').click();
    assert.equal(await page.evaluate(() => currentSlideIndex), 1);
    await page.evaluate(() => document.querySelector('.slide.active-slide .fragment').classList.add('visible'));
    await page.locator('#btn-prev-slide').click();
    assert.equal(await page.evaluate(() => currentSlideIndex), 0);
    await page.locator('.slide.active-slide h2').click();
    assert.equal(await page.evaluate(() => currentSlideIndex), 1);
    await page.locator('body').press('ArrowLeft');
    assert.equal(await page.evaluate(() => currentSlideIndex), 0);
    await page.locator('#btn-pres-view-mode').selectOption('web');
    assert.equal(await page.locator('.slide.active-slide').getAttribute('data-view-mode'), 'web');
    assert.equal(await page.locator('#step-indicator').isVisible(), true);
    await page.locator('#btn-next-slide').click();
    assert.equal(await page.evaluate(() => currentSlideIndex), 0);
    assert.equal(await page.locator('.slide.active-slide .fragment.visible').count(), 1);
    await page.locator('#btn-prev-slide').click();
    assert.equal(await page.evaluate(() => currentSlideIndex), 0);
    assert.equal(await page.locator('.slide.active-slide .fragment.visible').count(), 0);
    await page.locator('#btn-pres-view-mode').press('ArrowRight');
    assert.equal(await page.evaluate(() => currentSlideIndex), 0);
    await page.locator('#btn-pres-view-mode').selectOption('ppt');
    assert.equal(await page.locator('.btn-slide-mode-switch').first().inputValue(), 'ppt');
    await page.locator('#btn-pres-view-mode').selectOption('image');
    await page.evaluate(() => { nextStepOrSlide(); });
    assert.equal(await page.evaluate(() => currentSlideIndex), 1);
    assert.equal(await page.locator('.slide.active-slide').getAttribute('data-view-mode'), 'image');
    await page.evaluate(() => { exitPresentationMode(); });
    await page.locator('#lecture-view-mode').selectOption('web');
    await page.evaluate(() => { goHome(); openLecture('qa-images', true); });
    assert.equal(await page.locator('#btn-pres-view-mode').inputValue(), 'image');
    assert.equal(await page.evaluate(() => JSON.stringify(LECTURES) === qaOriginal), true);
    await page.reload();
    assert.equal(await page.evaluate(() => localStorage.getItem('mee101_preferred_view_mode_v1')), 'web');
    await page.evaluate(() => {
      LECTURES.splice(0, LECTURES.length, { id: 'qa-reloaded', title: 'Synthetic', week: 'QA', slides: [{ title: 'HTML', html: '<p>Reload check</p>' }] });
      openLecture('qa-reloaded', true);
    });
    assert.equal(await page.locator('#btn-pres-view-mode').inputValue(), 'image');
    await page.setViewportSize({ width: 1366, height: 900 });
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.slide.active-slide')).opacity) > 0.99);
    await page.screenshot({ path: '.jtmp/image-view-dropdown.png' });
    assert.deepEqual(errors, []);
    console.info('Passed: PNG pixels, original ratio, notes, HTML interaction, three modes, mobile, presentation, reload and unchanged lecture content.');
  } finally { await browser?.close(); server.kill(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
